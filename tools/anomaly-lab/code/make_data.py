#!/usr/bin/env python3
"""
make_data.py — bakes the anomaly-lab's Ken French monthly data into ../data.js.

The tool runs CAPM / FF3 / Carhart time-series regressions for ten
value-weighted decile portfolios per sort, live in the browser, so the raw
monthly series are shipped as one static ES module (no fetch, no backend —
site invariant). This script regenerates that module.

Sources (all Ken French data library,
https://mba.tuck.dartmouth.edu/pages/faculty/ken.french/data_library.html —
zips cached in the course tree at
"…/FIN30600 - Investments/Topics/Topic 5/code/data/"; refreshed 2026-10-07,
built by French from the 202608 CRSP database (the vintage is read from the
files); re-download the same names from …/ftp/<name>.zip to refresh):
  F-F_Research_Data_Factors_CSV.zip   Mkt-RF, SMB, HML, RF (monthly, %)
  F-F_Momentum_Factor_CSV.zip         Mom (= WML)          (monthly, %)
  Portfolios_Formed_on_BETA_CSV.zip   VW returns, 10 beta deciles
  Portfolios_Formed_on_ME_CSV.zip     VW returns, 10 size deciles
  Portfolios_Formed_on_BE-ME_CSV.zip  VW returns, 10 book-to-market deciles
  10_Portfolios_Prior_12_2_CSV.zip    VW returns, 10 momentum deciles

Sample: July 1963 (first month of the BETA file — same start as the Lecture 5
sort charts, see make_l5_data_figures.py in the course tree) through the
latest month present in ALL series. Values stay in French's units (percent
per month, 2 dp); missing (-99.99/-999) becomes null.

Usage:  python3 make_data.py          (writes ../data.js, prints a summary)
"""
import io
import json
import re
import zipfile
from datetime import date
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "data.js"
# course-tree cache (see docstring); override with a local ./data/ if present
CACHE_CANDIDATES = [
    HERE / "data",
    Path.home() / "Library/CloudStorage/Dropbox/Teaching/Notre Dame"
    / "FIN30600 - Investments/Topics/Topic 5/code/data",
]
DATA = next(p for p in CACHE_CANDIDATES if p.is_dir())

START = pd.Period("1963-07", "M")  # first month of the BETA file
VINTAGES = set()  # CRSP vintages seen in the zips (must be exactly one)

SORTS = {
    "beta": ("Portfolios_Formed_on_BETA_CSV.zip",
             "Value Weighted Returns -- Monthly",
             ["Lo 10"] + [f"Dec {k}" for k in range(2, 10)] + ["Hi 10"]),
    "size": ("Portfolios_Formed_on_ME_CSV.zip",
             "Average Value Weight Returns -- Monthly",
             ["Lo 10"] + [f"{k}-Dec" for k in range(2, 10)] + ["Hi 10"]),
    "bm":   ("Portfolios_Formed_on_BE-ME_CSV.zip",
             "Value Weight Returns -- Monthly",
             ["Lo 10"] + [f"{k}-Dec" for k in range(2, 10)] + ["Hi 10"]),
    "mom":  ("10_Portfolios_Prior_12_2_CSV.zip",
             "Value Weight Returns -- Monthly",
             ["Lo PRIOR"] + [f"PRIOR {k}" for k in range(2, 10)] + ["Hi PRIOR"]),
}


def _french_block(txt, marker):
    """Slice one data block out of a French CSV (blocks separated by blanks)."""
    lines = txt.splitlines()
    i0 = next(i for i, l in enumerate(lines) if marker in l)
    ih = next(i for i in range(i0, i0 + 5) if lines[i].startswith(","))
    rows = []
    for l in lines[ih + 1:]:
        if not re.match(r"^\s*\d{6},", l):
            break
        rows.append(l)
    df = pd.read_csv(io.StringIO("\n".join([lines[ih]] + rows)), index_col=0)
    df.index = pd.PeriodIndex(
        [pd.Period(f"{str(i)[:4]}-{str(i)[4:6]}", "M") for i in df.index],
        freq="M")
    df.columns = [c.strip() for c in df.columns]
    return df


def load(zname, marker, cols):
    with zipfile.ZipFile(DATA / zname) as z:
        txt = z.read(z.namelist()[0]).decode("latin1")
    m = re.search(r"(\d{6}) CRSP", txt)
    VINTAGES.add(m.group(1) if m else "?")
    df = _french_block(txt, marker)[cols].astype(float)
    return df.mask(df <= -99)  # -99.99/-999 = missing


def series_js(s):
    """Compact JS array literal: 2 dp, null for missing."""
    vals = ("null" if pd.isna(v) else format(v, ".2f") for v in s)
    return "[" + ",".join(vals) + "]"


def main():
    fac = load("F-F_Research_Data_Factors_CSV.zip", ",Mkt-RF",
               ["Mkt-RF", "SMB", "HML", "RF"])
    mom = load("F-F_Momentum_Factor_CSV.zip", ",Mom", ["Mom"])
    fac = fac.join(mom, how="inner").rename(columns={"Mom": "WML"})

    decs = {k: load(*spec) for k, spec in SORTS.items()}

    idx = fac.index
    for d in decs.values():
        idx = idx.intersection(d.index)
    idx = idx[idx >= START]
    fac = fac.loc[idx]
    decs = {k: d.loc[idx] for k, d in decs.items()}

    n = len(idx)
    start, end = idx[0], idx[-1]
    assert len(VINTAGES) == 1, f"mixed CRSP vintages: {VINTAGES}"
    vint = VINTAGES.pop()
    print(f"sample {start}..{end}  ({n} months)")

    parts = []
    parts.append(f"""// GENERATED by code/make_data.py — do not edit by hand.
// Ken French data library monthly series (percent/month, 2 dp, null =
// missing), {start}..{end}, {n} months, {vint} CRSP vintage. Sources,
// methodology, and refresh instructions: see code/make_data.py.
// Built {date.today().isoformat()}.

export const META = {{
  start: '{start}', end: '{end}', months: {n},
  vintage: '{vint} CRSP', built: '{date.today().isoformat()}',
}};

/** Monthly factor series, percent: mktrf, smb, hml, wml, rf. */
export const FACTORS = {{""")
    for key, col in [("mktrf", "Mkt-RF"), ("smb", "SMB"), ("hml", "HML"),
                     ("wml", "WML"), ("rf", "RF")]:
        parts.append(f"  {key}: {series_js(fac[col])},")
    parts.append("};\n")
    parts.append("""/** Value-weighted decile portfolio returns per sort, percent:
 * SORTS[sort][d] is decile d+1 (D1 = Lo … D10 = Hi), aligned to META. */
export const SORTS = {""")
    for key, d in decs.items():
        parts.append(f"  {key}: [")
        for c in d.columns:
            parts.append(f"    {series_js(d[c])},")
        parts.append("  ],")
    parts.append("};")

    OUT.write_text("\n".join(parts) + "\n")
    kb = OUT.stat().st_size / 1024
    print(f"wrote {OUT.name}  ({kb:.0f} KB)")

    # sanity anchors (full sample = the Topic 5 deck tables since 2026-10-07)
    import numpy as np
    for label, sub in [("full", idx)]:
        f = fac.loc[sub]
        print(f"[{label}] Mkt premium {f['Mkt-RF'].mean() * 12:.2f}%  "
              f"(n={len(sub)})")
        y = (decs["beta"].loc[sub].iloc[:, 0] - f["RF"]).dropna()
        x = f.loc[y.index, "Mkt-RF"]
        b, a = np.polyfit(x, y, 1)
        print(f"[{label}] beta-sort D1: avg {y.mean() * 12:.2f}  "
              f"beta {b:.2f}  alpha {a * 12:.2f}")


if __name__ == "__main__":
    main()
